-- Append-only, hash-chained audit log (ATLAS.md §15). One chain per tenant.
-- The app role can only INSERT and SELECT (default privileges of 0001); the triggers also stop the owner.
-- actor_id has no foreign key on purpose: deleting an account must not touch or block its history.

-- +goose Up
ALTER DEFAULT PRIVILEGES IN SCHEMA audit GRANT USAGE, SELECT ON SEQUENCES TO atlas_app;

CREATE TABLE audit.events (
  id        bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  tenant_id uuid NOT NULL DEFAULT NULLIF(current_setting('atlas.tenant_id', true), '')::uuid,
  at        timestamptz NOT NULL,
  actor_id  uuid,
  action    text NOT NULL,
  subject   text NOT NULL,
  detail    text NOT NULL DEFAULT '',
  prev_hash text NOT NULL,
  hash      text NOT NULL
);
CREATE INDEX events_tenant_id ON audit.events (tenant_id, id);

ALTER TABLE audit.events ENABLE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON audit.events USING (tenant_id = NULLIF(current_setting('atlas.tenant_id', true), '')::uuid);

-- +goose StatementBegin
CREATE FUNCTION audit.reject_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'audit.events is append-only';
END $$;
-- +goose StatementEnd
CREATE TRIGGER events_append_only BEFORE UPDATE OR DELETE ON audit.events FOR EACH ROW EXECUTE FUNCTION audit.reject_change();
CREATE TRIGGER events_no_truncate BEFORE TRUNCATE ON audit.events FOR EACH STATEMENT EXECUTE FUNCTION audit.reject_change();

-- +goose Down
DROP TABLE audit.events;
DROP FUNCTION audit.reject_change();
